//! The screens' TypeScript types come from ts-rs (`cargo test` writes them to src/lib/bindings).
//! This test adds the shared constants next to them, so neither side keeps its own copy.

use std::path::Path;

use crate::apply::SETTINGS_EVENT;
use crate::keyboard::{GERMAN_DEVICE_ID, LIGHT_COUNT, MAX_LEVEL, ONBOARD_SLOTS, POLLING_RATES, STATUS_EVENT, lighting_modes};
use crate::profiles::{MAX_NAME_LEN, PROFILES_EVENT};

#[test]
fn export_constants() {
    let dir = std::env::var("TS_RS_EXPORT_DIR").expect("set in .cargo/config.toml");
    let rates = POLLING_RATES.map(|hz| hz.to_string()).join(", ");
    let modes: Vec<String> = lighting_modes()
        .map(|m| {
            let options: Vec<String> = m.options.iter().map(|o| format!("\"{o}\"")).collect();
            let option_label = m.option_label.map_or("null".to_string(), |label| format!("\"{label}\""));
            format!(
                "  {}: {{ name: \"{}\", usesColor: {}, brightness: {}, speed: {}, optionLabel: {}, options: [{}], offered: {} }},",
                m.id,
                m.name,
                m.uses_color,
                m.brightness,
                m.speed,
                option_label,
                options.join(", "),
                m.offered
            )
        })
        .collect();
    let modes = modes.join("\n");
    let content = format!(
        "// Generated by `cargo test` from src-tauri/src/bindings.rs. Do not edit by hand.\n\n\
         export const STATUS_EVENT = \"{STATUS_EVENT}\";\n\
         export const SETTINGS_EVENT = \"{SETTINGS_EVENT}\";\n\
         export const PROFILES_EVENT = \"{PROFILES_EVENT}\";\n\n\
         /** Brightness and speed both run from 0 to this value. */\n\
         export const MAX_LEVEL = {MAX_LEVEL};\n\n\
         /** Polling rates in Hz, fastest first. */\n\
         export const POLLING_RATES = [{rates}] as const;\n\n\
         /** The keyboard's onboard profiles are numbered 0 to ONBOARD_SLOTS - 1. */\n\
         export const ONBOARD_SLOTS = {ONBOARD_SLOTS};\n\n\
         export const MAX_NAME_LEN = {MAX_NAME_LEN};\n\n\
         /** The German (ISO) MX 8.2, whose two extra keys the picture doesn't show yet. */\n\
         export const GERMAN_DEVICE_ID = {GERMAN_DEVICE_ID};\n\n\
         /** Lights in a pattern, by light number (column x 6 + row). */\n\
         export const LIGHT_COUNT = {LIGHT_COUNT};\n\n\
         /** A lighting effect: MagCrate's name, the settings it uses, its options (direction or pattern,\n\
          * in firmware order) and whether the MX 8.2 offers it. */\n\
         export type LightingMode = {{\n  name: string;\n  usesColor: boolean;\n  brightness: boolean;\n  \
         speed: boolean;\n  optionLabel: string | null;\n  options: readonly string[];\n  offered: boolean;\n}};\n\n\
         /** Lighting effects by mode ID. */\n\
         export const LIGHTING_MODES: Record<number, LightingMode> = {{\n{modes}\n}};\n",
    );
    std::fs::create_dir_all(&dir).expect("create the bindings folder");
    std::fs::write(Path::new(&dir).join("constants.ts"), content).expect("write constants.ts");
}
